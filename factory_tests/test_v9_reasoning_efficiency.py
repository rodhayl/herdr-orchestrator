class TestV9DeterministicEscalation(unittest.TestCase):
    """Validates bounded, deterministic escalation rules and non-escalatable error boundaries."""

    def setUp(self):
        self.policy = ReasoningPolicy.load()

    def test_eligible_failure_escalates_one_step_in_ladder(self):
        """A quality failure on attempt 1 at low effort escalates strictly to medium in same model family."""
        for fail_cat in ["DETERMINISTIC_TEST_FAILED", "REQUIREMENT_VALIDATION_FAILED", "INCOMPLETE_RESULT"]:
            next_effort, reason = self.policy.evaluate_escalation(
                current_effort="low",
                model_family="gemini-3.8-flash",
                failure_category=fail_cat,
                attempt_id=1,
                execution_class="routine"
            )
            self.assertEqual(next_effort, "medium")
            self.assertIn("ESCALATED", reason)

    def test_non_eligible_infra_failures_never_escalate(self):
        """Infrastructure and environmental failures must NEVER escalate reasoning effort."""
        for fail_cat in ["TIMEOUT", "TIMED_OUT", "AUTH_BLOCKED", "GIT_CONFLICT", "CONTEXT_COMPILATION_FAILED"]:
            next_effort, reason = self.policy.evaluate_escalation(
                current_effort="low",
                model_family="gemini-3.8-flash",
                failure_category=fail_cat,
                attempt_id=1,
                execution_class="routine"
            )
            self.assertIsNone(next_effort)
            self.assertIn("FAILURE_NOT_ELIGIBLE", reason)

    def test_bounded_escalation_cap_max_one_step(self):
        """Escalation is strictly capped at 1 step: attempt 2 failure cannot escalate further."""
        next_effort, reason = self.policy.evaluate_escalation(
            current_effort="medium",
            model_family="gemini-3.8-flash",
            failure_category="DETERMINISTIC_TEST_FAILED",
            attempt_id=2,  # Already escalated on attempt 1 -> attempt 2
            execution_class="routine"
        )
        self.assertIsNone(next_effort)
        self.assertIn("ESCALATION_LIMIT_REACHED", reason)

    def test_cannot_escalate_beyond_ladder_ceiling(self):
        """When already at the maximum ladder effort ('high'), escalation returns None."""
        next_effort, reason = self.policy.evaluate_escalation(
            current_effort="high",
            model_family="gemini-3.8-flash",
            failure_category="DETERMINISTIC_TEST_FAILED",
            attempt_id=1,
            execution_class="standard"
        )
        self.assertIsNone(next_effort)
        self.assertIn("ALREADY_AT_CEILING", reason)

    def test_project_policy_disable_escalation(self):
        """Project policy disabling effort escalation blocks all escalation."""
        proj = {"disable_effort_escalation": True}
        next_effort, reason = self.policy.evaluate_escalation(
            current_effort="low",
            model_family="gemini-3.8-flash",
            failure_category="DETERMINISTIC_TEST_FAILED",
            attempt_id=1,
            project_policy=proj
        )
        self.assertIsNone(next_effort)
        self.assertIn("ESCALATION_DISABLED_BY_PROJECT_POLICY", reason)

    def test_project_policy_max_effort_cap(self):
        """Project policy capping max_effort at medium prevents escalation to high."""
        proj = {"max_effort": "medium"}
        next_effort, reason = self.policy.evaluate_escalation(
            current_effort="medium",
            model_family="gemini-3.8-flash",
            failure_category="DETERMINISTIC_TEST_FAILED",
            attempt_id=1,
            project_policy=proj
        )
        self.assertIsNone(next_effort)
        self.assertIn("PROJECT_CEILING_REACHED", reason)


