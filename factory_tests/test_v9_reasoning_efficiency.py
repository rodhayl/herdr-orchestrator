class TestV9SchemaAndProvenance(unittest.TestCase):
    """Validates schema adherence, monotonic ladders, and provenance staleness checks."""

    def setUp(self):
        self.policy_path = PROJECT_ROOT / "reasoning_policy.json"
        self.assertTrue(self.policy_path.exists(), "reasoning_policy.json must exist")
        with open(self.policy_path, "r", encoding="utf-8") as f:
            self.policy_data = json.load(f)

    def test_policy_schema_structure(self):
        """Verifies policy has all required top-level and section keys."""
        policy = ReasoningPolicy.load(self.policy_path)
        self.assertEqual(policy.version, "9.0.0")
        self.assertEqual(policy.status, "VALID")
        self.assertIn("model_ladders", policy.data)
        self.assertIn("role_policy", policy.data)
        self.assertIn("task_policy", policy.data)
        self.assertIn("escalation_policy", policy.data)
        self.assertIn("provenance_hashes", policy.data)

    def test_monotonic_effort_ladders(self):
        """Verifies all certified model ladders are strictly ordered with no duplicates."""
        ladders = self.policy_data.get("model_ladders", {})
        self.assertIn("gemini-3.8-flash", ladders)
        self.assertEqual(ladders["gemini-3.8-flash"], ["low", "medium", "high"])

        self.assertIn("qwen3.8-max", ladders)
        self.assertEqual(ladders["qwen3.8-max"], ["low", "medium", "xhigh"])

        self.assertIn("claude-sonnet-4-6", ladders)
        self.assertEqual(ladders["claude-sonnet-4-6"], ["high"])

        for model, ladder in ladders.items():
            self.assertTrue(len(ladder) >= 1, f"Ladder for {model} must not be empty")
            self.assertEqual(len(ladder), len(set(ladder)), f"Ladder for {model} must not have duplicates")

    def test_provenance_validation_current_repo(self):
        """Verifies current repository governance files match recorded provenance hashes."""
        policy = ReasoningPolicy.load(self.policy_path)
        is_valid, drift_reasons = policy.check_staleness(PROJECT_ROOT)
        self.assertTrue(is_valid, f"Provenance drift detected unexpectedly: {drift_reasons}")
        self.assertEqual(len(drift_reasons), 0)

    def test_provenance_drift_detected_on_tampering(self):
        """Verifies that tampering with a recorded hash triggers drift detection."""
        tampered_data = copy.deepcopy(self.policy_data)
        tampered_data["provenance_hashes"]["harness_profiles_hash"] = "00000000000000000000000000000000"
        is_valid, drift_reasons = verify_policy_provenance(tampered_data, PROJECT_ROOT)
        self.assertFalse(is_valid)
        self.assertTrue(any("harness_profiles_hash" in r for r in drift_reasons))

    def test_malformed_policy_rejected(self):
        """Verifies MalformedReasoningPolicyError on invalid schemas."""
        bad_data = copy.deepcopy(self.policy_data)
        bad_data["schema_version"] = "1.0.0"
        with self.assertRaises(MalformedReasoningPolicyError):
            ReasoningPolicy(bad_data)

        bad_ladder = copy.deepcopy(self.policy_data)
        bad_ladder["model_ladders"]["gemini-3.8-flash"] = ["low", "low"]
        with self.assertRaises(MalformedReasoningPolicyError):
            ReasoningPolicy(bad_ladder)


