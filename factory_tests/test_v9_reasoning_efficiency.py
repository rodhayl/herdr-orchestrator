class TestV9FailpointsAndResume(unittest.TestCase):
    """Validates deterministic crash failpoints around reasoning selection and escalation."""

    def setUp(self):
        self.temp_dir = tempfile.TemporaryDirectory()
        self.test_plan_path = pathlib.Path(self.temp_dir.name) / "failpoint_plan.json"
        self.plan_data = {
            "plan_id": "test_v9_failpoints",
            "name": "V9 Failpoint Test Plan",
            "version": "3.0.0",
            "tasks": [
                {
                    "task_id": "task_v9_resilient",
                    "worker_id": "agy",
                    "task_type": "backend",
                    "execution_class": "routine",
                    "max_retries": 1,
                    "dependencies": [],
                    "allowed_paths": ["factory_tests/fixtures/**"]
                }
            ]
        }
        with open(self.test_plan_path, "w", encoding="utf-8") as f:
            json.dump(self.plan_data, f)
        self.orig_commit = subprocess.run(["git", "rev-parse", "HEAD"], cwd=str(PROJECT_ROOT), capture_output=True, text=True).stdout.strip()
        V9FakeWorkerAdapter.behavior = "SUCCESS"
        self.cfg_path = PROJECT_ROOT / "factory.json"

    def tearDown(self):
        self.temp_dir.cleanup()
        cur_commit = subprocess.run(["git", "rev-parse", "HEAD"], cwd=str(PROJECT_ROOT), capture_output=True, text=True).stdout.strip()
        if cur_commit != self.orig_commit:
            subprocess.run(["git", "reset", self.orig_commit], cwd=str(PROJECT_ROOT), capture_output=True)
        proc = subprocess.run(["git", "branch", "--list", "factory/run-*"], cwd=str(PROJECT_ROOT), capture_output=True, text=True)
        for br in proc.stdout.splitlines():
            b = br.strip().replace("*", "").strip()
            if b and "resilient" in b:
                subprocess.run(["git", "branch", "-D", b], cwd=str(PROJECT_ROOT), capture_output=True)
        subprocess.run(["git", "worktree", "prune"], cwd=str(PROJECT_ROOT), capture_output=True)

    def _run_failpoint_and_resume_test(self, failpoint_name: str, fail_first_attempt: bool = False):
        from tools.factory import RUNS_DIR

        with open(self.cfg_path, "r", encoding="utf-8") as f:
            orig_cfg = json.load(f)
        patched_cfg = copy.deepcopy(orig_cfg)
        patched_cfg["worker_registry"]["agy"]["adapter"] = "v9_fake_worker"
        with open(self.cfg_path, "w", encoding="utf-8") as f:
            json.dump(patched_cfg, f, indent=2)

        try:
            env = os.environ.copy()
            env["FACTORY_TEST_FAILPOINT"] = failpoint_name
            env["FACTORY_TEST_HARNESS"] = "1"
            if fail_first_attempt:
                env["V9_FAKE_WORKER_BEHAVIOR"] = "FAIL_ATTEMPT_1"
            env["PYTHONPATH"] = f"{PROJECT_ROOT}:{PROJECT_ROOT}/tools"

            # 1. Run triggers failpoint exit code 88
            proc = subprocess.run(
                [sys.executable, str(PROJECT_ROOT / "tools" / "factory.py"), "run", str(self.test_plan_path)],
                cwd=str(PROJECT_ROOT),
                env=env,
                capture_output=True,
                text=True
            )
            self.assertEqual(proc.returncode, 88, f"Expected 88 at failpoint {failpoint_name}, got {proc.returncode}: {proc.stderr}")

            # Discover latest created run
            runs = sorted(list(RUNS_DIR.glob("run-*")), key=lambda p: p.stat().st_mtime, reverse=True)
            self.assertTrue(len(runs) > 0)
            latest_run = runs[0]

            # 2. Resume without failpoint succeeds
            resume_env = os.environ.copy()
            resume_env.pop("FACTORY_TEST_FAILPOINT", None)
            resume_env.pop("V9_FAKE_WORKER_BEHAVIOR", None)
            resume_env["FACTORY_TEST_HARNESS"] = "1"
            resume_env["PYTHONPATH"] = f"{PROJECT_ROOT}:{PROJECT_ROOT}/tools"
            proc2 = subprocess.run(
                [sys.executable, str(PROJECT_ROOT / "tools" / "factory.py"), "resume", latest_run.name],
                cwd=str(PROJECT_ROOT),
                env=resume_env,
                capture_output=True,
                text=True
            )
            self.assertEqual(proc2.returncode, 0, f"Resume failed: {proc2.stderr}")
            with open(latest_run / "manifest.json", "r", encoding="utf-8") as mf:
                final_data = json.load(mf)
            self.assertEqual(final_data["final_status"], "COMPLETED")

            # Cleanup run directory and test fixture outputs
            if latest_run.exists():
                shutil.rmtree(latest_run, ignore_errors=True)
            for out_file in (PROJECT_ROOT / "factory_tests" / "fixtures").glob("output_*resilient*.txt"):
                try:
                    out_file.unlink()
                except Exception:
                    pass
        finally:
            with open(self.cfg_path, "w", encoding="utf-8") as f:
                json.dump(orig_cfg, f, indent=2)

    def test_failpoint_after_effort_selected(self):
        """Simulates crash at after_effort_selected and tests clean resume."""
        self._run_failpoint_and_resume_test("after_effort_selected", fail_first_attempt=False)

    def test_failpoint_after_low_attempt_failed(self):
        """Simulates crash at after_low_attempt_failed and tests clean resume."""
        self._run_failpoint_and_resume_test("after_low_attempt_failed", fail_first_attempt=True)

