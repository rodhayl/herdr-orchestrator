class V9FakeWorkerAdapter(WorkerAdapter):
    behavior = "SUCCESS"

    def prepare_environment(self, run_id, task_id, attempt_id, worktree_path):
        ws_id = f"v9-fake-ws-{task_id}-a{attempt_id}"
        pane_id = f"{ws_id}:p1"
        self.res_mgr.record_workspace(ws_id, pane_id, run_id=run_id)
        return {
            "workspace_id": ws_id,
            "pane_id": pane_id,
            "worktree_path": str(worktree_path)
        }

    def execute(self, run_id, task_id, attempt_id, worktree_path, prompt_file, schema_file, timeout, task_attempt_dir, env_info, model, effort=None):
        behavior = os.environ.get("V9_FAKE_WORKER_BEHAVIOR", getattr(self, "behavior", "SUCCESS"))
        if behavior == "FAIL_ATTEMPT_1" and attempt_id == 1:
            return {
                "exit_code": 1,
                "timed_out": False,
                "raw_output": "Deterministic test failure",
                "data": {"status": "FAILED", "state": "DETERMINISTIC_TEST_FAILED", "error": "AssertionError: simulated failure on attempt 1"}
            }
        dummy_file = worktree_path / "factory_tests" / "fixtures" / f"output_{task_id}_{run_id}.txt"
        dummy_file.parent.mkdir(parents=True, exist_ok=True)
        dummy_file.write_text(f"Generated by {task_id}\n", encoding="utf-8")
        return {
            "exit_code": 0,
            "timed_out": False,
            "raw_output": json.dumps({"status": "SUCCESS", "structured_output": {"summary": f"Completed {task_id}"}}),
            "data": {"status": "SUCCESS", "structured_output": {"task_id": task_id, "summary": f"Successfully finished {task_id}"}}
        }

    def cancel(self, run_id, task_id, attempt_id, env_info):
        return True


